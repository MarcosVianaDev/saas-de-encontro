const {BASE_URL,launch,testCredentials,login,selectEvent}=require('./helpers.cjs');
const assert=require('node:assert/strict');
const crypto=require('node:crypto');
(async()=>{
const browser=await launch();const errors=[];
try{
  const creds=testCredentials();
  const participant=await browser.newPage({viewport:{width:390,height:844}});
  participant.on('pageerror',e=>errors.push(e.message));
  await login(participant,creds.email);
  await participant.evaluate(()=>location.hash='mensagens');
  await participant.getByRole('button',{name:/Notificações/}).first().click();
  await participant.getByRole('heading',{name:'Notificações',exact:true}).waitFor();
  await participant.getByRole('button',{name:'Suporte',exact:true}).click();
  await participant.getByLabel('Como podemos ajudar?').waitFor();
  assert(await participant.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
  await participant.context().close();
  const admin=await browser.newPage({viewport:{width:1440,height:1000}});
  admin.on('pageerror',e=>errors.push(e.message));
  await login(admin,creds.adminEmail);
  await selectEvent(admin);
  await admin.locator('.adm-bottom').getByRole('button',{name:'Evento',exact:true}).click();
  await admin.getByRole('heading',{name:'Configurações',exact:true}).waitFor();
  await admin.locator('.adm-bottom').getByRole('button',{name:'Global',exact:true}).click();
  await admin.getByRole('heading',{name:'Administração Global',exact:true}).waitFor();
  await admin.locator('.adm-bottom').getByRole('button',{name:'Clientes',exact:true}).click();
  await admin.getByRole('button',{name:'+ Novo cliente',exact:true}).click();
  const contact='Contato '+crypto.randomUUID().slice(0,8),email='client-'+crypto.randomUUID()+'@example.invalid';
  await admin.getByLabel('Nome',{exact:true}).fill(contact);
  await admin.getByLabel('E-mail',{exact:true}).fill(email);
  await admin.getByLabel('Telefone',{exact:true}).fill('11999990000');
  await admin.getByRole('button',{name:'Cadastrar cliente',exact:true}).click();
  await admin.getByRole('heading',{name:contact,exact:true}).waitFor();
  await admin.getByRole('button',{name:'Completar / editar cadastro',exact:true}).click();
  await admin.getByLabel('Nome da organização',{exact:true}).fill('Cliente de teste '+contact);
  await admin.getByRole('button',{name:'Salvar alterações',exact:true}).click();
  await admin.getByRole('heading',{name:contact,exact:true}).waitFor();
  await admin.locator('.adm-bottom').getByRole('button',{name:'Eventos',exact:true}).click();
  await admin.getByRole('button',{name:'+ Novo evento',exact:true}).click();
  const clientOptions=await admin.getByLabel('Cliente',{exact:true}).locator('option').evaluateAll(options=>options.map(o=>({value:o.value,text:o.textContent})));
  const client=clientOptions.find(o=>o.text.includes(contact));assert(client);
  await admin.getByLabel('Cliente',{exact:true}).selectOption(client.value);
  await admin.getByLabel('Modalidade').selectOption('ONLINE');
  const name='Evento '+crypto.randomUUID().slice(0,8);
  await admin.getByLabel('Nome do evento',{exact:true}).fill(name);
  const local=date=>new Date(date.getTime()-date.getTimezoneOffset()*60000).toISOString().slice(0,16);
  await admin.locator('form').getByLabel('Início',{exact:true}).fill(local(new Date(Date.now()+3600000)));
  await admin.getByLabel('Término',{exact:true}).fill(local(new Date(Date.now()+14400000)));
  await admin.getByLabel('E-mail da conta responsável',{exact:true}).selectOption(email);
  await admin.getByRole('button',{name:'Criar evento',exact:true}).click();
  const card=admin.locator('section').filter({has:admin.getByRole('heading',{name,exact:true})}).last();
  await card.getByRole('button',{name:'Administrar evento',exact:true}).click();
  await admin.locator('.adm-bottom').getByRole('button',{name:'Evento',exact:true}).click();
  await admin.getByRole('button',{name:'Abrir evento',exact:true}).click();
  await admin.locator('form').getByRole('button',{name:'Abrir evento',exact:true}).click();
  await admin.getByRole('heading',{name:'Status: Aberto',exact:true}).waitFor();
  await admin.locator('.adm-bottom').getByRole('button',{name:'Global',exact:true}).click();
  await admin.locator('.global-administration').waitFor();
  await admin.locator('.adm-bottom').getByRole('button',{name:'Mais',exact:true}).click();
  await admin.getByRole('tab',{name:'Conta',exact:true}).click();
  await admin.getByRole('button',{name:'Sair da conta',exact:true}).filter({visible:true}).click();
  await admin.getByLabel('E-mail',{exact:true}).waitFor();
  assert.deepEqual(errors,[]);
  console.log('PASS: participant inbox/support, global/event contexts, separate client and event forms, responsible selection, manual opening and logout.');
}finally{await browser.close();}
})().catch(e=>{console.error(e);process.exit(1);});
